#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

function buildQuestionPayloads() {
  const root = path.join(__dirname, '../..');
  const source = fs.readFileSync(path.join(root, 'data/forge-data.js'), 'utf8');
  const context = { console, Math, Date };
  vm.createContext(context);
  vm.runInContext(source + '\nthis.BANKS=BANKS;this.SUBJECTS=SUBJECTS;this.RETIRED_BANKS=RETIRED_BANKS;', context);

  const output = path.join(root, 'data/question-payloads');
  fs.mkdirSync(output, { recursive: true });
  const bankSubjects = {};
  for (const [subjectKey, subject] of Object.entries(context.SUBJECTS)) {
    for (const bankId of subject.banks || []) bankSubjects[bankId] = subjectKey;
  }
  const bankMeta = {};
  const questionIndex = {subjects: {}, specs: {}, tags: {}, misconceptionSubjects: {}};
  for (const [id, bank] of Object.entries(context.BANKS)) {
    const questions = bank.questions || [];
    const subject = bankSubjects[id] || null;
    for (const question of questions) {
      if (subject) questionIndex.subjects[question.id] = subject;
      if (question.spec) questionIndex.specs[question.id] = question.spec;
      const tags = (Array.isArray(question.tag) ? question.tag : [question.tag]).filter(Boolean);
      if (tags.length) questionIndex.tags[question.id] = tags;
      if (subject) for (const tag of tags) questionIndex.misconceptionSubjects[tag] = subject;
    }
    bankMeta[id] = {
      label: bank.label,
      color: bank.color,
      subject: bankSubjects[id] || null,
      questionCount: questions.length,
      assignableQuestionCount: questions.filter(question => !question.type || question.type === 'fill_blank').length,
      crucibleQuestionCount: questions.filter(question => !question.type && question.reforge).length,
      questions: []
    };
  }
  fs.writeFileSync(path.join(root, 'data/forge-catalog.js'), `/* Generated by build-question-payloads.js. */\nwindow.SUBJECTS=${JSON.stringify(context.SUBJECTS)};\nwindow.BANKS=${JSON.stringify(bankMeta)};\n`);
  fs.writeFileSync(path.join(root, 'data/forge-question-index.js'), `/* Generated by build-question-payloads.js. */\nwindow.FORGE_QUESTION_INDEX=${JSON.stringify(questionIndex)};\n`);

  for (const [subjectKey, subject] of Object.entries(context.SUBJECTS)) {
    const banks = {};
    for (const bankId of subject.banks || []) if (context.BANKS[bankId]) banks[bankId] = context.BANKS[bankId];
    fs.writeFileSync(path.join(output, `${subjectKey}.js`), `ForgeData.register(${JSON.stringify(subjectKey)},${JSON.stringify(banks)});\n`);
  }
  fs.writeFileSync(path.join(output, 'retired.js'), `ForgeData.registerRetired(${JSON.stringify(context.RETIRED_BANKS || {})});\n`);
  console.log(`Built ${Object.keys(context.SUBJECTS).length} lazy question payloads.`);
}

if (require.main === module) buildQuestionPayloads();
module.exports = buildQuestionPayloads;
